function typingLesson(
  slug: string,
  titleUk: string,
  text: string,
  layout: "en" | "uk",
  free = false,
  difficulty = 1,
  titleEn?: string,
): CourseContent["units"][0]["lessons"][0] {
  const enTitle = titleEn ?? titleUk;
  return {
    slug,
    titleUk,
    titleEn: enTitle,
    baseXp: 12 + difficulty * 3,
    difficulty,
    isFree: free,
    exercises: [
      {
        id: `tp-${slug}`,
        type: "typing",
        promptUk: titleUk,
        promptEn: enTitle,
        text,
        layout,
        targetWpm: 20 + difficulty * 10,
      },
    ],
  };
}

