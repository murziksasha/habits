import type { CourseContent, LessonContent } from "./types.js";

function puzzle(
  id: string,
  promptUk: string,
  category: string,
  difficulty: number,
  options: string[],
  correctIndex: number,
  hintUk?: string,
): LessonContent["exercises"][0] {
  return {
    id,
    type: "logic_puzzle",
    promptUk,
    category,
    difficulty,
    options,
    correctIndex,
    hintUk,
  };
}

function lesson(
  slug: string,
  titleUk: string,
  difficulty: number,
  free: boolean,
  exercises: LessonContent["exercises"],
  titleEn?: string,
): LessonContent {
  return {
    slug,
    titleUk,
    titleEn: titleEn ?? titleUk,
    baseXp: 10 + difficulty * 4,
    difficulty,
    isFree: free,
    exercises,
  };
}

