function lesson(
  slug: string,
  titleUk: string,
  titleEn: string,
  difficulty: number,
  isFree: boolean,
  exercises: Exercise[],
  extra?: { isExam?: boolean; passThreshold?: number; baseXp?: number },
): LessonContent {
  return {
    slug,
    titleUk,
    titleEn,
    baseXp: extra?.baseXp ?? 12 + difficulty * 3,
    difficulty,
    isFree,
    isExam: extra?.isExam,
    passThreshold: extra?.passThreshold,
    exercises,
  };
}

function unit(
  slug: string,
  titleUk: string,
  titleEn: string,
  lessons: LessonContent[],
): UnitContent {
  return { slug, titleUk, titleEn, lessons };
}

function exam(
  slug: string,
  titleUk: string,
  titleEn: string,
  difficulty: number,
  exercises: Exercise[],
): LessonContent {
  return lesson(slug, titleUk, titleEn, difficulty, false, exercises, {
    isExam: true,
    passThreshold: 0.7,
    baseXp: 28,
  });
}

