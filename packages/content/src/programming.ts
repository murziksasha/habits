import type { CourseContent, Exercise, LessonContent, UnitContent } from "./types.js";
import { codeFill, codeRead, codeOrder, codeOrderAuto, concept, mcq, matchEx, why } from "./builders.js";

function lesson(
  slug: string,
  titleUk: string,
  titleEn: string,
  difficulty: number,
  isFree: boolean,
  exercises: Exercise[],
  baseXp = 12 + difficulty * 3,
  opts?: { isExam?: boolean; passThreshold?: number },
): LessonContent {
  return {
    slug,
    titleUk,
    titleEn,
    baseXp,
    difficulty,
    isFree,
    isExam: opts?.isExam,
    passThreshold: opts?.passThreshold,
    exercises,
  };
}

function examLesson(
  slug: string,
  titleUk: string,
  titleEn: string,
  difficulty: number,
  exercises: Exercise[],
): LessonContent {
  return lesson(slug, titleUk, titleEn, difficulty, false, exercises, 28, {
    isExam: true,
    passThreshold: 0.7,
  });
}

function unit(
  slug: string,
  titleUk: string,
  titleEn: string,
  lessons: LessonContent[],
): UnitContent {
  return { slug, titleUk, titleEn, lessons };
}

