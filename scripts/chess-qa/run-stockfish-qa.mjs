#!/usr/bin/env node
/**
 * Offline Stockfish QA for chess puzzles.
 *
 *   pnpm chess:qa                         # all puzzles → packages/content/src/chess-qa.generated.ts
 *   pnpm chess:qa -- --incremental        # only puzzles whose FEN/solution hash changed
 *   pnpm chess:qa -- --only id1,id2 --report /tmp/qa.txt --dry
 *
 * Needs a built @eduforge/content (pnpm --filter @eduforge/content build) and Stockfish
 * (STOCKFISH_PATH or /usr/games/stockfish). CI never runs this; the vitest gate reads the
 * committed output and fails when it is stale (FEN/solution hash changed).
 */
import { writeFileSync, existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { ROOT, loadChess, getEngineVersion, pool } from "./engine.mjs";
import { qaPuzzle, puzzleHash } from "./qa-puzzle.mjs";
import { qaPlan, planHash } from "./qa-plan.mjs";

const args = process.argv.slice(2);
const arg = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const only = arg("--only")?.split(",").filter(Boolean);
const reportPath = arg("--report");
const depth = Number(arg("--depth") ?? 16);
const jobs = Number(arg("--jobs") ?? 4);
const incremental = args.includes("--incremental");

export const QA_OUT = join(ROOT, "packages/content/src/chess-qa.generated.ts");

export function readQaFile(path = QA_OUT) {
  if (!existsSync(path)) return { engine: "", depth: 0, items: {} };
  const src = readFileSync(path, "utf8");
  const a = src.indexOf("/*QA-JSON*/") + "/*QA-JSON*/".length;
  return JSON.parse(src.slice(a, src.indexOf("/*END-QA-JSON*/")));
}

async function main() {
  const Chess = await loadChess();
  const content = await import(pathToFileURL(join(ROOT, "packages/content/dist/index.js")).href);
  const course = content.chessContent;
  const puzzles = [];
  for (const u of course.units)
    for (const l of u.lessons)
      for (const e of l.exercises) if (e.type === "chess_puzzle" || e.type === "chess_plan") puzzles.push({ ...e, unit: u.slug, lesson: l.slug, isExam: Boolean(l.isExam) });

  const previous = readQaFile();
  const targets = puzzles.filter((p) => {
    if (only) return only.includes(p.id);
    if (incremental) return previous.items[p.id]?.hash !== (p.type === "chess_plan" ? planHash(p) : puzzleHash(p));
    return true;
  });
  console.error(`QA ${targets.length}/${puzzles.length} puzzles, depth ${depth}, jobs ${jobs}`);
  let n = 0;
  const results = await pool(targets, jobs, async (p) => {
    // QA judges the authored line, not the alternatives it produced last time.
    const r =
      p.type === "chess_plan"
        ? await qaPlan(Chess, p, { depth })
        : await qaPuzzle(Chess, { ...p, acceptedAlternatives: undefined, alternativeLines: undefined }, { depth });
    n += 1;
    if (n % 10 === 0) console.error(`  ${n}/${targets.length}`);
    return [p.id, r];
  });
  const items = { ...previous.items };
  for (const [id, r] of results) {
    const { plies, ...rest } = r;
    items[id] = { ...rest, plies: plies?.map((p) => [p.san, p.score, p.best, p.bestScore]) };
  }
  const live = new Set(puzzles.map((p) => p.id));
  for (const id of Object.keys(items)) if (!live.has(id)) delete items[id];

  const report = [];
  for (const p of puzzles) {
    const r = items[p.id];
    if (r?.flags?.length) for (const f of r.flags) report.push(`${p.id}\t${p.unit}\t${p.isExam ? "exam" : "teach"}\t${f}`);
  }
  if (reportPath) writeFileSync(reportPath, report.join("\n") + "\n");
  if (!args.includes("--dry")) writeOut(items);
  console.error(`flags: ${report.length} on ${new Set(report.map((l) => l.split("\t")[0])).size} puzzles`);
}

function writeOut(items) {
  const sorted = Object.fromEntries(Object.keys(items).sort().map((k) => [k, items[k]]));
  const payload = { engine: getEngineVersion() || readQaFile().engine, depth, items: sorted };
  writeFileSync(
    QA_OUT,
    `/* eslint-disable */\n// GENERATED by scripts/chess-qa/run-stockfish-qa.mjs — do not edit by hand.\n// Re-run: pnpm chess:qa (needs Stockfish). The content gate compares hashes.\nexport const CHESS_QA: ChessQaFile = /*QA-JSON*/${JSON.stringify(payload, null, 1)}/*END-QA-JSON*/;\n\nexport type ChessQaRecord = {\n  hash: string;\n  kind?: "plan";\n  goal: "mate" | "win_material" | "draw" | "promote" | "best_move";\n  scores?: Array<number | null>;\n  acceptedAlternatives?: Record<string, string[]>;\n  alternativeLines?: string[][];\n  evalAfter: number | null;\n  flags: string[];\n  /** [san, score, engineBestUci, engineBestScore] per ply */\n  plies?: Array<[string, number | null, string, number]>;\n};\nexport type ChessQaFile = { engine: string; depth: number; items: Record<string, ChessQaRecord> };\n`,
  );
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
