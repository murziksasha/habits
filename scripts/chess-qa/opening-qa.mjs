#!/usr/bin/env node
/**
 * Offline Stockfish QA for opening repertoires (phase 7): the final position of every line
 * must be no worse than −50 cp for the repertoire side.
 *
 *   pnpm --filter @eduforge/chess-core build && node scripts/chess-qa/opening-qa.mjs [--depth 20]
 *
 * Writes packages/content/src/chess-openings-qa.generated.ts (checked by chess-openings.test.ts).
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { ROOT, analyse, mateIn, pool } from "./engine.mjs";

const args = process.argv.slice(2);
const depth = Number(args[args.indexOf("--depth") + 1] || 20);
const core = await import(pathToFileURL(join(ROOT, "packages/chess-core/dist/index.js")).href);
const jobsList = [];
for (const rep of core.REPERTOIRES) {
  for (const line of rep.lines) {
    const g = new core.Chess();
    for (const s of line.sans) g.move(s);
    jobsList.push({ rep, line, fen: g.fen() });
  }
}
const out = {};
for (const j of jobsList) {
  const r = await analyse(j.fen, { multipv: 1, depth, timeoutMs: 30000 });
  const top = r.lines[0];
  if (!top) {
    console.error("no analysis", j.line.key);
    process.exitCode = 1;
    continue;
  }
  const m = mateIn(top.score);
  // Score is from the side to move; convert to the repertoire side.
  const stm = j.fen.split(" ")[1];
  const sign = stm === j.rep.side ? 1 : -1;
  const cp = m === null ? top.score * sign : null;
  out[j.line.key] = { moves: j.line.sans.join(" "), cp, mate: m === null ? null : m * sign };
  console.log(j.line.key, cp ?? `M${m * sign}`);
}
const body = `// Generated by scripts/chess-qa/opening-qa.mjs (depth ${depth}). Scores from the repertoire side. Do not edit.
export type OpeningLineQa = { moves: string; cp: number | null; mate: number | null };
export const CHESS_OPENINGS_QA: Record<string, OpeningLineQa> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(join(ROOT, "packages/content/src/chess-openings-qa.generated.ts"), body);
