#!/usr/bin/env node
/**
 * Offline Stockfish QA for endgame drills (phase 6).
 *
 *   pnpm --filter @eduforge/content build && node scripts/chess-qa/endgame-drill-qa.mjs [--depth 24]
 *
 * Writes packages/content/src/chess-endgame-qa.generated.ts: the start evaluation of each drill
 * from the learner's view. The vitest gate checks win/promote ≥ +500 cp (or mate) and draw within ±80
 * and fails when a drill FEN changed without re-running this script.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { ROOT, analyse, mateIn, getEngineVersion } from "./engine.mjs";

const args = process.argv.slice(2);
const depth = Number(args[args.indexOf("--depth") + 1] || 24);
const content = await import(pathToFileURL(join(ROOT, "packages/content/dist/index.js")).href);
const drills = content.ENDGAME_DRILL_SPECS;
const out = {};
for (const d of drills) {
  const r = await analyse(d.fen, { multipv: 1, depth, timeoutMs: 60000 });
  const top = r.lines[0];
  if (!top) {
    console.error(`no analysis for ${d.id}`);
    process.exitCode = 1;
    continue;
  }
  const m = mateIn(top.score);
  out[d.id] = { fen: d.fen, cp: m === null ? top.score : null, mate: m, best: top.uci };
  console.log(d.id, d.goal, m === null ? `${top.score}cp` : `M${m}`, top.uci);
}
let version = "stockfish";
try {
  version = (await getEngineVersion()) ?? version;
} catch {
  /* ignore */
}
const body = `// Generated by scripts/chess-qa/endgame-drill-qa.mjs (${version}, depth ${depth}). Do not edit.
export type EndgameDrillQa = { fen: string; cp: number | null; mate: number | null; best: string };
export const CHESS_ENDGAME_QA: Record<string, EndgameDrillQa> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(join(ROOT, "packages/content/src/chess-endgame-qa.generated.ts"), body);
